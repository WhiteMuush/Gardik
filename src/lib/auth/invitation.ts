import { createHash, randomBytes } from "node:crypto"
import bcrypt from "bcryptjs"
import type { Prisma, PrismaClient } from "@prisma/client"

type Db = PrismaClient | Prisma.TransactionClient

// Long enough to survive a weekend, short enough that a forgotten link stops being a way in.
export const INVITATION_TTL_HOURS = 72

// Mirrors emailAndPassword in server.ts; the maximum matters because bcrypt ignores bytes past 72.
export const MIN_PASSWORD_LENGTH = 12
export const MAX_PASSWORD_LENGTH = 72

// 32 random bytes in base64url, since the token alone stands between an inbox and a set password.
export function generateToken(): string {
  return randomBytes(32).toString("base64url")
}

// Only the SHA-256 hash is stored; bcrypt adds nothing on 256 bits of entropy and would slow the rate-limited accept.
export function hashToken(token: string): string {
  return createHash("sha256").update(token).digest("hex")
}

export function passwordProblem(password: string): string | null {
  if (password.length < MIN_PASSWORD_LENGTH) {
    return `Use at least ${MIN_PASSWORD_LENGTH} characters`
  }
  if (Buffer.byteLength(password, "utf8") > MAX_PASSWORD_LENGTH) {
    return `Use at most ${MAX_PASSWORD_LENGTH} bytes`
  }
  return null
}

export function isExpired(expiresAt: Date, now: Date = new Date()): boolean {
  return expiresAt.getTime() <= now.getTime()
}

// Issues a fresh invitation, voids every outstanding one for that user, and returns the raw token once.
export async function issueInvitation(
  db: Db,
  {
    userId,
    createdByUserId,
    now = new Date(),
    // Generated by default; the bootstrap passes its own, since a generated token would have to be printed.
    token = generateToken(),
    ttlHours = INVITATION_TTL_HOURS,
  }: {
    userId: string
    // Null for an invitation the system issued with no administrator behind it.
    createdByUserId: string | null
    now?: Date
    token?: string
    ttlHours?: number
  }
): Promise<{ token: string; expiresAt: Date }> {
  const expiresAt = new Date(now.getTime() + ttlHours * 60 * 60 * 1000)

  await db.userInvitation.updateMany({
    where: { userId, consumedAt: null },
    data: { consumedAt: now },
  })

  await db.userInvitation.create({
    data: { userId, tokenHash: hashToken(token), expiresAt, createdByUserId },
  })

  return { token, expiresAt }
}

export type ConsumeResult =
  { ok: true; userId: string } | { ok: false; reason: "invalid" | "weak_password"; message: string }

// Sets the password, verifies the email, clears a forced rotation and ends sessions; callers give one message per failure.
export async function consumeInvitation(
  db: PrismaClient,
  { token, password, now = new Date() }: { token: string; password: string; now?: Date }
): Promise<ConsumeResult> {
  const invalid = {
    ok: false as const,
    reason: "invalid" as const,
    message: "This invitation link is no longer valid",
  }

  const problem = passwordProblem(password)
  if (problem) return { ok: false, reason: "weak_password", message: problem }

  const invitation = await db.userInvitation.findUnique({
    where: { tokenHash: hashToken(token) },
    select: { id: true, userId: true, expiresAt: true, consumedAt: true },
  })
  if (!invitation || invitation.consumedAt || isExpired(invitation.expiresAt, now)) return invalid

  // Hashed outside the transaction, since bcrypt at 12 rounds would hold the row lock for hundreds of milliseconds.
  const hashedPassword = await bcrypt.hash(password, 12)

  return db.$transaction(async (tx) => {
    // Claim and check are one statement, so of two requests with the same token exactly one gets count 1.
    const claimed = await tx.userInvitation.updateMany({
      where: { id: invitation.id, consumedAt: null },
      data: { consumedAt: now },
    })
    if (claimed.count !== 1) return invalid

    const credential = await tx.account.findFirst({
      where: { userId: invitation.userId, providerId: "credential" },
      select: { id: true },
    })
    if (credential) {
      await tx.account.update({ where: { id: credential.id }, data: { password: hashedPassword } })
    } else {
      await tx.account.create({
        data: {
          accountId: invitation.userId,
          providerId: "credential",
          userId: invitation.userId,
          password: hashedPassword,
        },
      })
    }

    await tx.user.update({
      where: { id: invitation.userId },
      data: { emailVerified: true, mustChangePassword: false },
    })

    // Ends every session of this user, so an intruder's session dies when a compromised account is recovered.
    await tx.session.deleteMany({ where: { userId: invitation.userId } })

    return { ok: true as const, userId: invitation.userId }
  })
}
